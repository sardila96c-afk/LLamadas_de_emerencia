"""SIMULACION Y PREDICCIÓN"""

class SimuladorDatos:

    def __init__(self, df):
        self.df = df # Se iniciaa con el DataFrame limpio


    def promedio_diario(self):
        """
        Calcula el promedio de emergencias por día.
        Agrupa las llamadas por fecha y obtiene el promedio total.
        """

        emergencias_dia = self.df.groupby(
            self.df['fecha'].dt.date
        ).size()

        return emergencias_dia.mean()




    def predecir(self, dias_futuros=7, ruido=200):
        """
        Genera una predicción de emergencias para los próximos días.
        dias_futuros: cantidad de días a predecir
        ruido: variación aleatoria para simular comportamiento real
        """

        promedio = self.promedio_diario()
        predicciones = []

        for i in range(dias_futuros):

            fecha_futura = (
                datetime.now() + timedelta(days=i+1)
            ).date()

            estimado = round(
                np.random.normal(promedio, ruido)
            )

            predicciones.append([fecha_futura, estimado])

        return pd.DataFrame(
            predicciones,
            columns=["fecha", "prediccion"]
        )



def recomendacion_ambulancias(df, top_n=3):
    """
    Genera recomendaciones de asignación de ambulancias.

    Selecciona las zonas con mayor número de incidentes
    y sugiere aumentar recursos en esas áreas.

    Parámetros:
    - df: DataFrame limpio
    - top_n: número de zonas más críticas a mostrar
    """

    zonas = df['zona'].value_counts().head(top_n) # Obtiene las zonas con más incidentes

    recomendaciones = []

    for zona, cantidad in zonas.items():
        recomendaciones.append(
            f"Asignar más ambulancias en {zona} ({cantidad} incidentes)"
        )

    return recomendaciones



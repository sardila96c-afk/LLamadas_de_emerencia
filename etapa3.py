"""Calcular Estadisticas y tendencias"""

class AnalizadorDatos:
    """
    Esta clase se encarga de extraer información útil del dataset limpio.
    Calcula estadísticas, tendencias y patrones en los datos.
    """

    def __init__(self, df):
        self.df = df

    #Clasificar incidentes
    def clasificar_incidentes(self): #Cuenta cuántos incidentes hay por tipo
        return self.df['tipo'].value_counts()

    # Emergencia más frecuente
    def analizar_frecuencia(self):  # Identifica el tipo de emergencia más frecuente y cuántas veces ocurre.
        conteo = self.df['tipo'].value_counts()
        return conteo.idxmax(), conteo.max()

    # Zona más crítica
    def identificar_zonas_criticas(self): #Identifica la zona con mayor número de emergencias.
        conteo = self.df['zona'].value_counts()
        return conteo.idxmax(), conteo.max()


    def emergencias_por_dia(self): # Agrupa las emergencias por fecha (día)y cuenta cuántas ocurren cada día.
        return self.df.groupby(
            self.df['fecha'].dt.date
        ).size().sort_index()

    def promedio_movil(self, ventana=3): #Calcula el promedio móvil para suavizar los datos. Ayuda a ver tendencias reales eliminando ruido.
        datos = self.emergencias_por_dia()
        return datos.rolling(ventana).mean()

    def tabla_tipo_gravedad(self):
        """
        Crea una tabla cruzada entre tipo de incidente y gravedad.
        Permite ver qué tan graves son los distintos incidentes.
        """
        return pd.crosstab(
            self.df['tipo'],
            self.df['gravedad']
        )

    def tendencia_emergencias(self):
      """
        Calcula la tendencia de emergencias en el tiempo
        usando una regresión lineal simple, calcula:
        pendiente (si sube o baja)
        intercepto
        """
      datos = self.emergencias_por_dia()

      dias = np.arange(len(datos))
      valores = datos.values

      coef = np.polyfit(dias, valores, 1)

      return coef[0], coef[1]  # pendiente, intercepto

    def emergencias_por_hora(self): #Cuenta cuántas emergencias ocurren en cada hora del día. Permite identificar horas pico.
      self.df['hora'] = self.df['fecha'].dt.hour
      return self.df['hora'].value_counts().sort_index()


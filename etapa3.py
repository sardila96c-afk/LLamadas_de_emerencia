class LimpiarDatos: #Esta clase se encarga de limpiar y preparar los datos. Corrige errores, estandariza valores y deja el dataset listo para análisis.
  def __init__(self, df):
    self.df = df # DataFrame original

     # Valores válidos esperados
    self.zonas_validas = ["Norte", "Sur", "Centro", "Este", "Oeste"]
    self.tipos_validos = ["Accidente", "Incendio", "Enfermedad", "Caida", "Derrame"]
    self.gravedades_validas = [1, 2, 3, 4, 5]
    columnas_necesarias = ["fecha", "zona", "tipo", "gravedad"]



    #Verificación de columnas obligatorias
    for col in columnas_necesarias: 
        if col not in self.df.columns:
            raise ValueError(f"Falta la columna: {col}")

   # ZONAS
  def limpiar_zonas(self):  #Limpia la columna 'zona', Elimina espacios, Corrige formato (Mayúscula inicial), Reemplaza valores inválidos por 'No identificada'

    self.df['zona'] = self.df['zona'].astype(str).str.strip().str.title()

    self.df.loc[
        ~self.df['zona'].isin(self.zonas_validas),
        'zona'
    ] = 'No identificada'


  def resumen_zonas(self): #conteo de zonas
        return self.df['zona'].value_counts()

  def errores_zonas(self): #Cuenta cuántos registros quedaron como inválidos
        return (self.df['zona'] == 'No identificada').sum()


    # -------- TIPOS --------
  def limpiar_tipos(self): #Limpia la columna 'tipo', Corrige formato, Reemplaza valores inválidos por 'No identificado'

    self.df['tipo'] = self.df['tipo'].astype(str).str.strip().str.title()

    self.df.loc[
        ~self.df['tipo'].isin(self.tipos_validos),
        'tipo'
    ] = 'No identificado'




  def resumen_tipos(self): #conteo de tipos de emergencias
        return self.df['tipo'].value_counts()

  def errores_tipos(self): #Cuenta cuántos registros quedaron como inválidos
        return (self.df['tipo'] == 'No identificado').sum()


    #gravedad

  def limpiar_gravedad(self): #Limpia la columna 'gravedad', Convierte a número, Valores fuera de rango (1-5) a 0, NaN a 0

    self.df['gravedad'] = pd.to_numeric(self.df['gravedad'], errors='coerce')

    self.df.loc[
        ~self.df['gravedad'].between(1, 5),
        'gravedad'
    ] = 0

    self.df['gravedad'] = self.df['gravedad'].fillna(0).astype(int)

  def resumen_gravedad(self): #conteo de gravedades
          return self.df['gravedad'].value_counts()

  def errores_gravedad(self): #Cuenta cuántos registros quedaron como inválidos
          return (self.df['gravedad'] == 0).sum()



    #fechas

  def limpiar_fechas(self):
    """
    Limpia la columna 'fecha'
     Convierte a formato datetime
    Valores inválidos a fecha actual
      """


    # convertir a datetime
    self.df['fecha'] = pd.to_datetime(
        self.df['fecha'],
        errors='coerce'
    )

     #rellenar con fecha válida
    fecha_reemplazo = pd.Timestamp.now()

    self.df['fecha'] = self.df['fecha'].fillna(fecha_reemplazo)


  def crear_hora(self):
    """
    Crea una nueva columna 'hora' a partir de la fecha.
    Se usa para análisis de horas pico.
    """

    self.df['hora'] = self.df['fecha'].dt.hour

